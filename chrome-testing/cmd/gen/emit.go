package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// maxGalleryValues bounds how many values a specimen lists. The grammar set is
// shown in full up to this; only genuinely huge sets (e.g. 147 named colors) are
// truncated, and the gallery paginates the difference strip.
const maxGalleryValues = 50

// emit writes generated/codex-data.jsx (window.CODEX) and manifest.tsv from the
// rendered properties, grouping them into the gallery families.
func emit(props []Property, outDir string) {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		panic(err)
	}

	byFam := map[string][]Property{}
	for _, p := range props {
		fam := classify(p.Name)
		byFam[fam] = append(byFam[fam], p)
	}

	var b strings.Builder
	b.WriteString("/* GENERATED by chrome-testing/cmd/gen — do not edit by hand.\n")
	b.WriteString("   Every value below is derived from the CSS EBNF grammar via the gluon v2\n")
	b.WriteString("   parser + proto reflection. Representative samples are used ONLY at the\n")
	b.WriteString("   open-ended leaf types (length/number/color-token/…); all composites are\n")
	b.WriteString("   walked. The frontend renders purely from window.CODEX. */\n\n")
	b.WriteString("(function () {\n")
	b.WriteString("  const v = (value, css, label) => ({ value, css, note: \"\", label: label || value });\n")
	b.WriteString("  const families = [\n")

	number := 0
	var manifest strings.Builder
	totalProps := 0
	var nPureComplete, nPureTrunc, nAssisted, nEmpty int
	valuesByName := map[string][]string{}

	for _, fam := range families {
		list := byFam[fam.ID]
		sort.Slice(list, func(i, j int) bool { return list[i].Name < list[j].Name })

		b.WriteString("    {\n")
		fmt.Fprintf(&b, "      id: %s, sigil: %s, title: %s, blurb: %s,\n",
			js(fam.ID), js(fam.Sigil), js(fam.Title), js(fam.Blurb))
		fmt.Fprintf(&b, "      demo: %s, sampleKind: %s, group: %s, focus: %t, gallery: false,\n",
			js(fam.Demo), js(fam.SampleKind), js(fam.Group), fam.Focus)
		fmt.Fprintf(&b, "      count: %d,\n", len(list))
		b.WriteString("      properties: [\n")

		for _, p := range list {
			number++
			totalProps++
			switch {
			case p.Provenance == "empty":
				nEmpty++
			case p.Provenance == "assisted":
				nAssisted++
			case p.Truncated:
				nPureTrunc++
			default:
				nPureComplete++
			}

			vals := p.Values
			shown := len(vals)
			if shown > maxGalleryValues {
				vals = vals[:maxGalleryValues]
				shown = maxGalleryValues
			}
			valuesByName[p.Name] = vals
			vt := inferValueType(vals)
			def := ""
			if len(vals) > 0 {
				def = vals[min(1, len(vals)-1)]
			}
			ebnf := ""
			if p.Syntax != "" {
				ebnf = p.Name + " =\n  " + p.Syntax
			}
			desc := description(p)

			fmt.Fprintf(&manifest, "%s\t%s\t%s\t%s\t%d\t%s\t%d\n",
				p.Name, fam.ID, p.Prop, vt, len(p.Values), p.Provenance, p.TrueCount)

			b.WriteString("        {\n")
			fmt.Fprintf(&b, "          number: %d, name: %s, maturity: \"modern\",\n", number, js(p.Name))
			fmt.Fprintf(&b, "          description: %s,\n", js(desc))
			fmt.Fprintf(&b, "          experimental: %t, nonstandard: %t, deprecated: %t, warning: %s,\n",
				p.Experimental, p.Nonstandard, p.Deprecated, js(p.Warning))
			fmt.Fprintf(&b, "          syntax: %s, ebnf: %s,\n", js(p.Syntax), js(ebnf))
			fmt.Fprintf(&b, "          valueType: %s, defaultValue: %s, related: [],\n", js(vt), js(def))
			fmt.Fprintf(&b, "          provenance: %s, truncated: %t, trueCount: %d, shown: %d,\n",
				js(p.Provenance), p.Truncated, p.TrueCount, shown)
			fmt.Fprintf(&b, "          assists: %s,\n", assistsJS(p.Assists))
			b.WriteString("          values: [\n")
			for _, val := range vals {
				css := p.Name + ": " + val + ";"
				fmt.Fprintf(&b, "            v(%s, %s),\n", js(val), js(css))
			}
			b.WriteString("          ],\n")
			b.WriteString("        },\n")
		}
		b.WriteString("      ],\n")
		b.WriteString("    },\n")
	}

	b.WriteString("  ];\n")
	fmt.Fprintf(&b, "  window.CODEX = {\n")
	fmt.Fprintf(&b, "    total: %d,\n", totalProps)
	fmt.Fprintf(&b, "    stats: { pureComplete: %d, pureTruncated: %d, assisted: %d, empty: %d },\n",
		nPureComplete, nPureTrunc, nAssisted, nEmpty)
	b.WriteString("    familyCount: families.filter((f) => f.group !== \"galleries\").length,\n")
	b.WriteString("    galleryCount: families.filter((f) => f.group === \"galleries\").length,\n")
	b.WriteString("    families,\n")
	b.WriteString("    byId: Object.fromEntries(families.map((f) => [f.id, f])),\n")
	b.WriteString("  };\n")
	b.WriteString("})();\n")

	dataPath := filepath.Join(outDir, "codex-data.jsx")
	if err := os.WriteFile(dataPath, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	manPath := filepath.Join(outDir, "manifest.tsv")
	if err := os.WriteFile(manPath, []byte(manifest.String()), 0o644); err != nil {
		panic(err)
	}
	valJSON, _ := json.MarshalIndent(valuesByName, "", " ")
	if err := os.WriteFile(filepath.Join(outDir, "values.json"), valJSON, 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("Wrote %s (%d properties across %d families)\n", dataPath, totalProps, len(families))
	fmt.Printf("  pure-complete %d · pure-truncated %d · assisted %d · empty %d\n",
		nPureComplete, nPureTrunc, nAssisted, nEmpty)
	fmt.Printf("Wrote %s\n", manPath)
}

// description is the MDN summary paragraph shown below the property name. The
// generation provenance lives only in the banner, so this is purely editorial.
func description(p Property) string {
	if p.Description != "" {
		return p.Description
	}
	return fmt.Sprintf("The %s CSS property.", p.Name)
}

func assistsJS(as []Assist) string {
	if len(as) == 0 {
		return "[]"
	}
	parts := make([]string, 0, len(as))
	for _, a := range as {
		samples := make([]string, 0, len(a.Samples))
		for _, s := range a.Samples {
			samples = append(samples, js(s))
		}
		parts = append(parts, fmt.Sprintf("{ type: %s, samples: [%s] }", js(a.Type), strings.Join(samples, ", ")))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func js(s string) string {
	bts, _ := json.Marshal(s)
	return string(bts)
}
